COMPLETE = b"TESTS_FINISHED\n"
# This program is immutable host configuration, never generated by a worker.
TEST_RUNNER = b"""import json
from pathlib import Path
context = json.loads(Path('/inputs/validation-context.json').read_text())
archive = json.loads(Path('/inputs/workspace.json').read_text())
workspace = {f['path']: f['text'] for f in archive['files']}
count = [0]
def check(condition):
    count[0] += 1
    if not condition:
        raise AssertionError('trusted assertion failed')
status, code = 'PASS', 0
try:
    script = Path('/inputs/approved-test.py').read_bytes()
    exec(compile(script, '/inputs/approved-test.py', 'exec'),
         {'workspace': workspace, 'check': check, '__builtins__': __builtins__})
    if count[0] != context['test_count']:
        status, code = 'FAIL', 1
except Exception:
    status, code = 'FAIL', 1
report = {'schema': 'aioa.trusted-test-result.v1',
          'stage': context['stage'], 'profile_digest': context['profile_digest'],
          'patchset_sha256': context['patchset_sha256'],
          'tests_run': count[0], 'status': status, 'exit_code': code}
print(json.dumps(report, sort_keys=True, separators=(',', ':')), flush=True)
Path('/artifacts/test-report-complete.txt').write_bytes(b'TESTS_FINISHED\\n')
"""


@dataclass(frozen=True, slots=True)
class TrustedTestProfile:
    profile_id: str
    scripts: tuple[tuple[str, bytes], ...] = field(repr=False)
    counts: tuple[tuple[str, int], ...]

    def __post_init__(self):
        logical_id(self.profile_id)
        for value in (self.scripts, self.counts):
            require(type(value) is tuple and len(value) == 3, "FIXED_TEST_PROFILE")
            require(
                all(type(row) is tuple and len(row) == 2 for row in value),
                "FIXED_TEST_PROFILE",
            )
            require(tuple(row[0] for row in value) == TEST_STAGES, "FIXED_TEST_PROFILE")
        for _, script in self.scripts:
            require(
                type(script) is bytes and 0 < len(script) <= 65536, "FIXED_TEST_PROFILE"
            )
        for _, count in self.counts:
            bounded_int(count, 1, 256)

    @property
    def digest(self):
        return canonical_sha256(
            {
                "id": self.profile_id,
                "scripts": [
                    [
                        stage,
                        hashlib.sha256(script).hexdigest(),
                        dict(self.counts)[stage],
                    ]
                    for stage, script in self.scripts
                ],
            }
        )

    def context(self, stage, patchset):
        require(stage in TEST_STAGES, "TEST_STAGE")
        return {
            "schema": "aioa.trusted-test-context.v1",
            "stage": stage,
            "profile_digest": self.digest,
            "patchset_sha256": patchset.patchset_sha256,
            "test_count": dict(self.counts)[stage],
        }


def _context(context):
    require(
        type(context) is dict
        and set(context)
        == {"schema", "stage", "profile_digest", "patchset_sha256", "test_count"}
        and context["schema"] == "aioa.trusted-test-context.v1"
        and context["stage"] in TEST_STAGES,
        "TEST_CONTEXT",
    )
    digest(context["profile_digest"])
    digest(context["patchset_sha256"])
    bounded_int(context["test_count"], 1, 256)


def decode_test_report(stdout, context):
    _context(context)
    require(type(stdout) is str and len(stdout.encode()) <= 8192, "TEST_REPORT_BOUNDS")
    try:
        parser = JsonlFramer()
        rows = parser.feed(stdout.encode())
        parser.finish()
    except (ValueError, UnicodeError):
        raise ValueError("TEST_REPORT_FORMAT") from None
    require(len(rows) == 1, "TEST_REPORT_COUNT")
    row = rows[0]
    require(
        set(row)
        == {
            "schema",
            "stage",
            "profile_digest",
            "patchset_sha256",
            "tests_run",
            "status",
            "exit_code",
        }
        and row["schema"] == "aioa.trusted-test-result.v1",
        "TEST_REPORT_SCHEMA",
    )
    require(
        all(
            row[key] == context[key]
            for key in ("stage", "profile_digest", "patchset_sha256")
        ),
        "TEST_REPORT_BINDING",
    )
    bounded_int(row["tests_run"], 0, context["test_count"])
    require(
        type(row["exit_code"]) is int and row["status"] in ("PASS", "FAIL"),
        "TEST_REPORT_EXIT",
    )
    require(
        (
            row["status"] == "PASS"
            and row["exit_code"] == 0
            and row["tests_run"] == context["test_count"]
        )
        or (row["status"] == "FAIL" and row["exit_code"] == 1),
        "FALSE_TEST_REPORT",
    )
    return row["status"], row["exit_code"]


def _json_bytes(data):
    def pairs(values):
        result = {}
        for key, value in values:
            require(key not in result, "DUPLICATE_ARCHIVE_KEY")
            result[key] = value
        return result

    require(
        type(data) is bytes and 0 < len(data) <= 1048576, "WORKSPACE_ARCHIVE_BOUNDS"
    )
    try:
        return json.loads(
            data.decode("utf-8"),
            object_pairs_hook=pairs,
            parse_constant=lambda _: require(False, "ARCHIVE_CONSTANT"),
        )
    except (UnicodeError, json.JSONDecodeError):
        raise ValueError("WORKSPACE_ARCHIVE_FORMAT") from None


def workspace_tree_digest(data):
    value = _json_bytes(data)
    require(
        type(value) is dict
        and set(value) == {"schema", "files"}
        and value["schema"] == "aioa.validation-workspace.v1"
        and type(value["files"]) is list
        and 0 < len(value["files"]) <= 256,
        "WORKSPACE_ARCHIVE_SCHEMA",
    )
    rows, names = [], set()
    for entry in value["files"]:
        require(
            type(entry) is dict and set(entry) == {"path", "mode", "text"},
            "WORKSPACE_ARCHIVE_SCHEMA",
        )
        path = normalize_patch_relative_path(entry["path"])
        require(
            path.casefold() not in names
            and type(entry["mode"]) is int
            and entry["mode"] in (0o600, 0o644, 0o700, 0o755)
            and type(entry["text"]) is str
            and "\x00" not in entry["text"],
            "WORKSPACE_ARCHIVE_ENTRY",
        )
        names.add(path.casefold())
        raw = entry["text"].encode("utf-8")
        require(
            not contains_sensitive_material(entry["text"]),
            "WORKSPACE_SENSITIVE_CONTENT",
        )
        require(len(raw) <= 1048576, "WORKSPACE_ARCHIVE_BOUNDS")
        rows.append([path, hashlib.sha256(raw).hexdigest(), len(raw), entry["mode"]])
    return canonical_sha256(sorted(rows))


def pack_workspace(root, patchset):
    require(type(patchset) is PatchSet, "PATCHSET_REQUIRED")
    patchset.verify_digest()
    tree = _snapshot(root)
    require(tree.digest == patchset.final_tree_sha256, "VALIDATION_TREE_CHANGED")
    try:
        files = [
            {
                "path": path,
                "mode": item.identity.mode,
                "text": item.content.decode("utf-8"),
            }
            for path, item in sorted(tree.files.items())
        ]
    except UnicodeError:
        raise ValueError("VALIDATION_TEXT_ONLY") from None
    raw = canonical_json_bytes(
        {"schema": "aioa.validation-workspace.v1", "files": files}
    )
    require(
        workspace_tree_digest(raw) == patchset.final_tree_sha256,
        "VALIDATION_TREE_BINDING",
    )
    return raw


@dataclass(frozen=True, slots=True)
class PreparedValidationStep:
    stage: str
    route: CoreToolRoute = field(repr=False)
    principal: object = field(repr=False)
    arguments: dict = field(repr=False)

    def __post_init__(self):
        require(
            self.stage in TEST_STAGES
            and type(self.route) is CoreToolRoute
            and self.route.bound_variant is SANDBOX
            and type(self.route.executor) is LinuxSandboxBroker,
            "CORE_SANDBOX_ROUTE_REQUIRED",
        )
        require(
            type(self.arguments) is dict
            and set(self.arguments)
            == {"session_id", "warrant", "operation", "reservation", "completion"},
            "VALIDATION_ARGUMENTS",
        )
        self.route.core.require(
            self.principal, Capability.COMMIT, scope=self.route.scope
        )


class CoreSandboxValidation:
    def __init__(self, journal, prepare, *, profile=None, cancel=None):
        require(
            type(journal) is CoreIntentJournal and callable(prepare),
            "EXISTING_CORE_REQUIRED",
        )
        require(
            profile is None or type(profile) is TrustedTestProfile, "FIXED_TEST_PROFILE"
        )
        require(cancel is None or type(cancel) is CancellationToken, "CANCEL_TOKEN")
        self.journal, self.prepare, self.profile, self.cancel = (
            journal,
            prepare,
            profile,
            cancel,
        )

    def open(self, root, patchset):
        require(
            type(self.profile) is TrustedTestProfile and type(patchset) is PatchSet,
            "VALIDATION_NOT_CONFIGURED",
        )
        archive = pack_workspace(root, patchset)
        prepared = self.prepare(root, patchset)
        require(
            type(prepared) is tuple
            and len(prepared) == 3
            and all(type(s) is PreparedValidationStep for s in prepared)
            and tuple(s.stage for s in prepared) == TEST_STAGES,
            "VALIDATION_STAGES",
        )
        for step in prepared:
            require(step.route.journal is self.journal, "SECOND_CORE_DENIED")
            config = step.route.executor.config
            op = step.arguments["operation"]
            config.registry.validate(op)
            spec = config.inputs()[op["payload"]["recipe_id"]]
            expected = {
                "test-report-complete.txt": {
                    "sha256": hashlib.sha256(COMPLETE).hexdigest(),
                    "bytes": len(COMPLETE),
                }
            }
            files = {
                "recipe.py": TEST_RUNNER,
                "approved-test.py": dict(self.profile.scripts)[step.stage],
                "validation-context.json": canonical_json_bytes(
                    self.profile.context(step.stage, patchset)
                ),
                "workspace.json": archive,
            }
            require(
                set(spec["files"]) == set(files) and spec["expected"] == expected,
                "VALIDATION_INPUTS",
            )
            for name, data in files.items():
                require(
                    spec["manifest"][name] == hashlib.sha256(data).hexdigest(),
                    "VALIDATION_INPUT_PIN",
                )
                path = Path(spec["files"][name])
                require(
                    read_evidence_file(path.parent, path.name) == data,
                    "VALIDATION_INPUT_CHANGED",
                )
        # Recheck after host preparation. The broker also pins each input at release.
        require(pack_workspace(root, patchset) == archive, "VALIDATION_TREE_CHANGED")
        return _CoreValidationSession(self, patchset, prepared)


class _CoreValidationSession:
    def __init__(self, owner, patchset, steps):
        self.owner, self.patchset, self.steps = owner, patchset, steps
        self.index, self.closed, self.cleanup_failed = 0, False, False
        self.failure_code = None

    def run(self, stage):
        require(
            not self.closed and self.index < 3 and stage == TEST_STAGES[self.index],
            "VALIDATION_ORDER",
        )
        step = self.steps[self.index]
        self.index += 1  # An uncertain dispatch never grants a retry.
        args = step.arguments
        warrant = args["warrant"]
        status, code, evidence = (
            "UNKNOWN",
            None,
            canonical_sha256({"unresolved": warrant.digest()}),
        )
        try:
            step.route.dispatch(step.principal, **args, cancel=self.owner.cancel)
            matching = []
            for run in step.route.executor.config.root.glob("run-*"):
                if not (run / "receipt.json").exists():
                    continue
                raw = read_evidence_file(run, "receipt.json")
                receipt = _json_bytes(raw)
                if receipt.get("warrant_digest") == warrant.digest():
                    matching.append((raw, receipt))
            require(len(matching) == 1, "VALIDATION_RECEIPT_REQUIRED")
            raw, receipt = matching[0]
            evidence = hashlib.sha256(raw).hexdigest()
            clean = (
                receipt.get("cgroup_absent_after_cleanup") is True
                and receipt.get("unit_terminal_observed") is True
                and receipt.get("cgroup_populated_zero_directly_observed") is True
            )
            self.cleanup_failed = not clean
            require(
                clean and receipt["status"] == "READBACK_VERIFIED",
                "VALIDATION_UNRESOLVED",
            )
            step.route.reconcile(step.principal, warrant, 1)

            def load(tx):
                return self.owner.journal._load(tx, warrant)[1]["resolution"]

            stored = self.owner.journal._run(step.principal, Capability.COMMIT, load)
            resolved = Reconciliation.from_dict(stored)
            require(
                resolved.outcome.to_dict()["contract_type"] == "Applied"
                and resolved.receipt.digest == "sha256:" + evidence,
                "VALIDATION_CORE_RECEIPT",
            )
            status, code = decode_test_report(
                receipt["observations"]["worker_terminal"]["stdout"],
                self.owner.profile.context(stage, self.patchset),
            )
            # Canonical Core evidence joins the report to the exact approved
            # sandbox operation. A caller-created ValidationStep is not proof.
            data = {
                "schema": "aioa.trusted-validation.v1",
                "stage": stage,
                "status": status,
                "exit_code": code,
                "patchset_sha256": self.patchset.patchset_sha256,
                "profile_digest": self.owner.profile.digest,
                "warrant_digest": warrant.digest(),
                "evidence_digest": evidence,
                "operation_digest": warrant.operation_hash,
                "warrant": warrant.to_dict(),
            }
            key = canonical_sha256(["aioa.trusted-validation.v1", warrant.digest()])

            def save(tx):
                from runtime.memory_patch.audit import append_domain_event
                from runtime.memory_patch.persistence.idempotency import (
                    OperationBinding,
                )

                current = self.owner.journal._load(tx, warrant)[1]
                require(current["resolution"] == stored, "VALIDATION_CORE_CHANGED")
                prior = tx.get(RecordKind.OPERATION, key)
                if prior is not None:
                    require(
                        canonical_json_bytes(prior.payload)
                        == canonical_json_bytes(data),
                        "VALIDATION_RECORD_CONFLICT",
                    )
                    return
                row = StoredRecord(RecordKind.OPERATION, key, step.route.scope, 1, data)
                tx.insert(row)
                binding = OperationBinding.bind(
                    "validation-" + key,
                    "TRUSTED_TEST_REPORT",
                    {"record_digest": row.payload_digest},
                )
                append_domain_event(
                    tx,
                    binding,
                    event_id="validation-audit-" + key,
                    proof_id="validation-proof-" + key,
                    resource_id=key,
                    before=None,
                    after=status,
                    content_digest=row.payload_digest,
                    at=self.owner.journal.ledger.clock(),
                )

            self.owner.journal._run(step.principal, Capability.COMMIT, save)
        except Exception as error:
            status, code = "UNKNOWN", None
            self.failure_code = (
                str(error)
                if re.fullmatch(r"[A-Z0-9_]{1,96}", str(error))
                else "VALIDATION_UNRESOLVED"
            )
            if self.owner.cancel is not None and self.owner.cancel.cancelled:
                status = "CANCELLED"
            # Unknown/malformed output never becomes a repairable test failure.
        return ValidationStep(
            stage,
            status,
            code,
            self.patchset.patchset_sha256,
            self.owner.profile.digest,
            evidence,
            warrant.digest(),
        )

    def close(self):
        self.closed = True
        return int(self.cleanup_failed)
